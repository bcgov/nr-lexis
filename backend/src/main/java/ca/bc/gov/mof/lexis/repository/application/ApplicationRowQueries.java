package ca.bc.gov.mof.lexis.repository.application;

/** Direct equivalents of LEXIS application cursors. */
public final class ApplicationRowQueries {

  /**
   * The row of LEXIS.FIND_APPLICATION_BY_NUMBER without its package join and per-package
   * GET_APPLICATION_APPROVAL_DATE call, which scans the application audit table. The inner joins
   * keep the cursor's filter: an application with an unknown status, reason or applicant type has
   * no row.
   */
  public static final String APPLICATION_BY_NUMBER =
      """
      SELECT
        EEA.APPLICATION_NUMBER,
        EEA.FED_APPLICATION_NUMBER,
        EEA.APPLICATION_DATE,
        EEA.TERM_DAYS,
        EEA.RECEIVED_DATE,
        EEA.EXEMPTION_APPLICATION_VOLUME,
        EEA.AVERAGE_LOG_VOLUME,
        EEA.PRODUCT_LOCATION,
        EEA.ENTRY_USERID,
        EEA.ENTRY_TIMESTAMP,
        EEA.EXPORT_SCHEDULE_ID,
        EEA.AGENT_CLIENT_NUMBER,
        EEA.AGENT_CLIENT_LOCATION_CODE,
        EEA.OWNER_CLIENT_NUMBER,
        EEA.OWNER_CLIENT_LOCATION_CODE,
        EEA.EXEMPTION_NUMBER,
        EEA.EXPORT_EXEMPTION_REASON_CODE,
        EEA.EXPORT_APPLICATION_STATUS_CODE,
        EEA.EXPORT_APPLICANT_TYPE_CODE,
        EEA.ORG_UNIT_NO,
        EEA.EXPORT_PRODUCT_TYPE_CODE,
        EEA.EXPORT_JURISDICTION_CODE,
        EEA.EXPORT_GROWTH_TYPE_CODE,
        EEA.AGENT_CONTACT_NAME,
        EEA.OWNER_CONTACT_NAME,
        EEA.OIC_INDICATOR,
        ES.ADVERTISING_DATE,
        OU.ORG_UNIT_NAME AS REGION
      FROM EXPORT_EXEMPTION_APPLICATION EEA
      LEFT JOIN EXPORT_SCHEDULE ES
        ON ES.EXPORT_SCHEDULE_ID = EEA.EXPORT_SCHEDULE_ID
      INNER JOIN EXPORT_APPLICATION_STATUS_CODE EASC
        ON EASC.EXPORT_APPLICATION_STATUS_CODE = EEA.EXPORT_APPLICATION_STATUS_CODE
      INNER JOIN EXPORT_EXEMPTION_REASON_CODE EERC
        ON EERC.EXPORT_EXEMPTION_REASON_CODE = EEA.EXPORT_EXEMPTION_REASON_CODE
      INNER JOIN EXPORT_APPLICANT_TYPE_CODE EATC
        ON EATC.EXPORT_APPLICANT_TYPE_CODE = EEA.EXPORT_APPLICANT_TYPE_CODE
      LEFT JOIN ORG_UNIT OU
        ON OU.ORG_UNIT_NO = EEA.ORG_UNIT_NO
      WHERE EEA.APPLICATION_NUMBER = ?
      """;

  /**
   * The rows of LEXIS.FIND_APPLICATION_BY_EXEMPTION, one per application, without its package join
   * and per-package approval date call. The cursor had no defined order; this one is by number.
   */
  public static final String APPLICATIONS_BY_EXEMPTION =
      """
      SELECT
        EEA.APPLICATION_NUMBER,
        EEA.EXEMPTION_APPLICATION_VOLUME,
        EEA.OWNER_CLIENT_NUMBER,
        EEA.AGENT_CLIENT_NUMBER,
        EEA.OWNER_CLIENT_LOCATION_CODE,
        EEA.AGENT_CLIENT_LOCATION_CODE,
        EEA.EXPORT_APPLICANT_TYPE_CODE,
        EEA.OWNER_CONTACT_NAME,
        EEA.AGENT_CONTACT_NAME,
        FCO.CLIENT_NAME AS OWNER_COMPANY_NAME,
        AFCO.CLIENT_NAME AS AGENT_COMPANY_NAME,
        EEA.EXPORT_JURISDICTION_CODE,
        EEA.EXPORT_PRODUCT_TYPE_CODE,
        EEA.EXPORT_APPLICATION_STATUS_CODE,
        EASC.DESCRIPTION AS STATUS_DESCRIPTION
      FROM EXPORT_EXEMPTION_APPLICATION EEA
      INNER JOIN EXPORT_APPLICATION_STATUS_CODE EASC
        ON EASC.EXPORT_APPLICATION_STATUS_CODE = EEA.EXPORT_APPLICATION_STATUS_CODE
      INNER JOIN EXPORT_EXEMPTION_REASON_CODE EERC
        ON EERC.EXPORT_EXEMPTION_REASON_CODE = EEA.EXPORT_EXEMPTION_REASON_CODE
      INNER JOIN EXPORT_APPLICANT_TYPE_CODE EATC
        ON EATC.EXPORT_APPLICANT_TYPE_CODE = EEA.EXPORT_APPLICANT_TYPE_CODE
      LEFT JOIN THE.V_CLIENT_PUBLIC FCO
        ON FCO.CLIENT_NUMBER = EEA.OWNER_CLIENT_NUMBER
      LEFT JOIN THE.V_CLIENT_PUBLIC AFCO
        ON AFCO.CLIENT_NUMBER = EEA.AGENT_CLIENT_NUMBER
      WHERE EEA.EXEMPTION_NUMBER = ?
      ORDER BY EEA.APPLICATION_NUMBER
      """;

  private ApplicationRowQueries() {}
}
